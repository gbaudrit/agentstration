// Reuse the product's bundled Tabler symbols without shipping the entire sprite.
import fs from 'node:fs';
const sprite=fs.readFileSync('../../Agentstration.Web.Components/wwwroot/tabler/tabler-sprite.svg','utf8');
const names=['robot','tool','book','database','plug-connected','cpu','schema','file-text','cube','server','package','puzzle','key','clock','route','building','search'];
const icons={};
for(const name of names){
 const symbol=sprite.match(new RegExp('<symbol[^>]*id="tabler-'+name+'"[^>]*>([\\s\\S]*?)</symbol>'));
 if(!symbol)throw new Error('Missing product Tabler symbol: '+name);
 const svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="white" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">'+symbol[1]+'</svg>';
 icons[name]='data:image/svg+xml,'+encodeURIComponent(svg);
}
fs.writeFileSync('resource-icons.generated.ts','// Generated by generate-resource-icons.mjs from the product Tabler sprite. MIT: ../../Agentstration.Web.Components/wwwroot/tabler/LICENSE.txt\nexport const resourceIcons:Readonly<Record<string,string>>='+JSON.stringify(icons,null,2)+';\n');
